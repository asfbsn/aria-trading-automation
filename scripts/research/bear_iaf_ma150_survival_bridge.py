#!/usr/bin/env python3
"""Bear IAF MA150 Forward Resistance-Hold Bridge Script.

Statistically compares two bear entry-gate tiers ("current" 7-of-7 vs the INCREMENTAL
signals "structural_2of3" adds beyond current -- see the conf_s23-and-not-conf_curr
filter below, fixes a double-count CodeRabbit caught 2026-08-31) on
the probability that the underlying stock stays below its signal-day MA150
resistance level over a 30-trading-day forward window across walk-forward backtest
windows generated by the investing-algorithm-framework (v8.10.0).

Isolated evaluation script -- does not modify aria-trading codebase.
"""
